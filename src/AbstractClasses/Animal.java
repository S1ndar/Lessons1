package AbstractClasses;

public abstract class Animal {  // абстрактный класс (концепция)
    public void eat() {         // исполбзуется тогда когда мы хотим создать иерархию класса, но класс родитель несамостоятельный
    	System.out.println("I am eating"); // все животные будут есть одинаково (то чего нет у интерфейсов)
    }
    
    public abstract void makeSound();      // но звуки у всех разные (все как у интерфейсов)
    
    // Интерфейс - то что объект класса умеет делать (действия)
    // Абстрактные классы - то чем этот объект является (сущность)
    
    // P.S класс может имплементить множество интерфейсов, НО наследоваться только от одного класса  
    
    // В моем понимании abstractClass = defoltClass + interface
}
