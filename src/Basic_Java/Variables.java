package Basic_Java;

public class Variables {

	public static void main(String[] args) {
		
		int myInt = 557;                   // 32
		short myShort = 3266;              // 16
		long myLong = 2624624698722235678L;// 64
		                           
		double myDouble = 235.35234567890; // 64
		float myFloat = 2362.4F;           // 32 
		
		char myChar = 'a';                 // 8
		boolean myBoolean = false;          
		
		byte myByte = 127;                 // 8
        System.out.println(myInt);
        
	}

}
